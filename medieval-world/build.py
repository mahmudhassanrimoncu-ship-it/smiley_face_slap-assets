#!/usr/bin/env python3
"""Builds the whole world kit. Needs only Python 3.10+, numpy and Pillow.

    pip install numpy pillow
    python3 build.py

Outputs (all regenerated every run):
    blueprints/   3 blueprint sheets (SVG + PNG)
    terrain/      heightmaps (16-bit PNG + RAW) and ground-cover masks
    model/        3D blockout of the whole world (.glb)
    data/         every building, tree, road, wall, field and landmark (JSON + CSV)
"""
import csv
import json
import math
import sys
import time
from pathlib import Path

import numpy as np
from PIL import Image

sys.path.insert(0, str(Path(__file__).parent / "src"))

from blueprint import castle_sheet, main_sheet, town_sheet  # noqa: E402
from config import HEIGHT_RANGE, REALM, WORLD_SIZE  # noqa: E402
from export3d import export_glb  # noqa: E402
from layout import build_layout  # noqa: E402
from surface import (LAYERS, attach_heights, build_masks, find_bridges, place_trees,  # noqa: E402
                     preview_image)
from terrain import build_heightmap  # noqa: E402

ROOT = Path(__file__).parent
T0 = time.time()


def log(msg):
    print(f"[{time.time() - T0:6.1f}s] {msg}", flush=True)


def out(*parts):
    p = ROOT.joinpath(*parts)
    p.parent.mkdir(parents=True, exist_ok=True)
    return p


def to_u16(H):
    return np.round(np.clip(H / HEIGHT_RANGE, 0, 1) * 65535).astype(np.uint16)


DISTRICTS = {"C": "Ashford Castle", "T": "Ashford town", "W": "Westbrook", "E": "Eastmere",
             "S": "Southfold", "A": "St. Hilda's Abbey", "O": "Countryside"}


def write_catalog(W):
    """A readable list of every building, grouped by district."""
    from collections import Counter
    lines = [f"# {REALM} - building catalogue", "",
             "Every building in the world, generated by `build.py`. Positions are metres from the map's",
             "north-west corner (x = east, y = south); z is the floor height. `Facing` is the compass",
             "direction of the front door. W x D is the footprint, Wall is the wall height above the",
             "highest ground under the building, Roof is the extra height of the roof.", ""]
    for code, name in DISTRICTS.items():
        rows = [b for b in W.buildings if b["district"] == code]
        if not rows:
            continue
        kinds = Counter(b["type"] for b in rows)
        lines += [f"## {name} ({len(rows)} buildings)", "",
                  ", ".join(f"{n} {k.replace('_', ' ')}" for k, n in kinds.most_common()), "",
                  "| ID | Name | Type | x | y | z | Facing | W x D (m) | Wall | Roof | Floors | Material |",
                  "|---|---|---|---:|---:|---:|---:|---|---:|---|---:|---|"]
        for b in rows:
            size = f"{b['w']:.1f} x {b['d']:.1f}" if b["shape"] != "round" else f"round, {b['w']:.1f} across"
            lines.append(f"| {b['id']} | {b['name']} | {b['type'].replace('_', ' ')} | {b['x']:.1f} | {b['y']:.1f} | "
                         f"{b['z']:.1f} | {b['heading']:.0f}° | {size} | {b['h']:.1f} | {b['roof']} {b['roof_h']:.1f} | "
                         f"{b['floors']} | {b['material']} |")
        lines.append("")
    out("data", "CATALOG.md").write_text("\n".join(lines))


def main():
    W = build_layout()
    W.realm = REALM
    log(f"layout: {len(W.buildings)} buildings, {len(W.roads)} roads, {len(W.fields)} field strips")
    H = build_heightmap(W)
    log(f"terrain: {H.min():.1f} m .. {H.max():.1f} m")
    weights = build_masks(W, H)
    place_trees(W, H)
    find_bridges(W, H)
    attach_heights(W, H)
    river = [w for w in W.waters if w["kind"] == "river"][0]
    lake = [w for w in W.waters if w["kind"] == "lake"][0]
    for p in W.props:
        if p["type"] == "stepping_stones":
            j = int(np.argmin(np.hypot(river["line"][:, 0] - p["x"], river["line"][:, 1] - p["y"])))
            p["top"] = float(river["levels"][j])
        if p["type"] in ("jetty", "boat"):
            p["top"] = lake["level"]
    log(f"trees: {len(W.trees)}, bridges: {len(W.bridges)}")

    # ---------------------------------------------------------------- terrain files
    u16 = to_u16(H)
    Image.fromarray(u16).save(out("terrain", "heightmap_2049.png"))
    u16.astype("<u2").tofile(out("terrain", "heightmap_2049.r16"))
    H17 = np.asarray(Image.fromarray(H, mode="F").resize((2017, 2017), Image.BICUBIC))
    Image.fromarray(to_u16(H17)).save(out("terrain", "heightmap_2017_unreal.png"))
    Image.fromarray((np.clip(H / HEIGHT_RANGE, 0, 1) * 255).astype(np.uint8)).save(out("terrain", "heightmap_preview_8bit.png"))
    for k in LAYERS:
        Image.fromarray((np.clip(weights[k], 0, 1) * 255).astype(np.uint8)).save(out("terrain", "masks", f"{k}.png"))
    rgb = preview_image(weights, H)
    water = np.zeros(H.shape, bool)
    for w in W.waters:  # paint water on the colour preview so it reads like a map
        if "level" in w:
            k = (H.shape[0] - 1) / WORLD_SIZE
            rx, ry = (w.get("rx", 0) + w.get("width", 0)) * 1.3, (w.get("ry", 0) + w.get("width", 0)) * 1.3
            y0, y1 = int(max(w["cy"] - ry, 0) * k), int(min(w["cy"] + ry, WORLD_SIZE) * k)
            x0, x1 = int(max(w["cx"] - rx, 0) * k), int(min(w["cx"] + rx, WORLD_SIZE) * k)
            water[y0:y1, x0:x1] |= H[y0:y1, x0:x1] < w["level"]
    lvl = np.full(H.shape, -1.0, np.float32)
    rd = W.river_dist
    from geom import polyline_field
    for w in W.waters:
        if w["kind"] in ("river", "stream"):
            d, s = polyline_field(w["line"][::2], H.shape[0], WORLD_SIZE / (H.shape[0] - 1), w["width"])
            cum = np.concatenate([[0], np.cumsum(np.hypot(*np.diff(w["line"][::2], axis=0).T))])
            lv = np.interp(s, cum, w["levels"][::2])
            water |= (d < w["width"] / 2 + 0.5) & (H < lv + 0.3)
    rgb[water] = (rgb[water] * 0.3 + np.array([52, 104, 150]) * 0.7).astype(np.uint8)
    Image.fromarray(rgb).save(out("terrain", "ground_colour_preview.png"))
    Image.fromarray(rgb).resize((1024, 1024), Image.LANCZOS).save(out("terrain", "ground_colour_preview_small.png"))
    log("terrain files written")

    # ---------------------------------------------------------------- data
    data = dict(
        realm=REALM,
        units="metres",
        coordinates=dict(origin="north-west corner of the map", x="metres east", y="metres south",
                         z="metres above the heightmap's zero (black)", heading="compass direction the front door "
                         "faces: 0 north, 90 east, 180 south, 270 west"),
        size_m=WORLD_SIZE,
        heightmap=dict(file="terrain/heightmap_2049.png", resolution=2049, metres_per_pixel=WORLD_SIZE / 2048,
                       height_range_m=HEIGHT_RANGE, encoding="16-bit: value / 65535 * 256 = metres"),
        ground_layers=LAYERS,
        landmarks=W.landmarks,
        buildings=W.buildings,
        walls=W.walls,
        bridges=W.bridges,
        roads=[dict(id=r["id"], name=r["name"], kind=r["kind"], width=r["width"], surface=r["surface"],
                    points=[[round(float(x), 1), round(float(y), 1), float(z)] for (x, y), z in
                            zip(r["line"][::3], r["z"][::3])]) for r in W.roads],
        water=[dict(id=w["id"], name=w["name"], kind=w["kind"], width=w.get("width"), level=w.get("level"),
                    points=[[round(float(x), 1), round(float(y), 1)] + ([float(w["levels"][i])] if "levels" in w else [])
                            for i, (x, y) in enumerate(w["line"]) if i % 3 == 0 or "levels" not in w])
               for w in W.waters],
        fields=W.fields, crofts=W.crofts, pastures=[dict(name=p["name"], poly=[list(map(lambda v: round(v, 1), q)) for q in p["poly"]]) for p in W.pastures],
        orchards=W.orchards, forests=W.forests, props=W.props, trees=W.trees,
    )
    with open(out("data", "world.json"), "w") as f:
        json.dump(data, f, indent=1, default=lambda o: o.tolist() if hasattr(o, "tolist") else float(o))
    cols = ["id", "name", "type", "district", "x", "y", "z", "heading", "w", "d", "h", "roof", "roof_h",
            "floors", "material", "shape", "resident", "trade", "group"]
    with open(out("data", "buildings.csv"), "w", newline="") as f:
        wr = csv.DictWriter(f, cols, extrasaction="ignore")
        wr.writeheader()
        for b in W.buildings:
            wr.writerow(b)
    with open(out("data", "trees.csv"), "w", newline="") as f:
        wr = csv.DictWriter(f, ["x", "y", "z", "species", "height", "group"])
        wr.writeheader()
        wr.writerows(W.trees)
    with open(out("data", "landmarks.csv"), "w", newline="") as f:
        wr = csv.DictWriter(f, ["n", "name", "x", "y", "desc"])
        wr.writeheader()
        wr.writerows(W.landmarks)
    write_catalog(W)
    log("data written")

    # ---------------------------------------------------------------- 3D
    export_glb(W, H, out("model", "ashford_vale_blockout.glb"), terrain_step=4)
    export_glb(W, H, out("model", "ashford_vale_preview.glb"), terrain_step=8, tree_stride=2)
    log("3D models written")

    # ---------------------------------------------------------------- blueprints
    out("blueprints", "01_master_site_plan.svg").write_text(main_sheet(W, H))
    out("blueprints", "02_castle_detail.svg").write_text(castle_sheet(W, H))
    out("blueprints", "03_town_detail.svg").write_text(town_sheet(W, H))
    log("blueprints written")
    W.H = H
    return W


if __name__ == "__main__":
    main()
